#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	char	*ch;
	int		i;

	i = 0;
	while (s[i])
	{
		if (s[i] == c)
		{
			ch = (char *)(s + i);
			return (ch);
		}
		i++;
	}
	return (NULL);
}
